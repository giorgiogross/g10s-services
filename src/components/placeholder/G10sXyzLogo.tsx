export const LOGO_WIDTH = 853;
export const LOGO_HEIGHT = 603;

const DISC = { cx: 426.5, cy: 510, rx: 426.5, ry: 90 };
const LETTER = { h: 96, w: 82, t: 30 }; // letter height, width and stroke thickness

function letterPolygons(): string[] {
  const { h, w, t } = LETTER;
  const top = DISC.cy - h / 2;
  const bottom = DISC.cy + h / 2;
  const half = w / 2;
  const bar = t * 0.8;
  const p = (...xy: number[]) => xy.join(" ");
  const x = (cx: number) => [
    p(cx - half, top, cx - half + t, top, cx + half, bottom, cx + half - t, bottom),
    p(cx + half, top, cx + half - t, top, cx - half, bottom, cx - half + t, bottom),
  ];
  const y = (cx: number) => {
    const join = DISC.cy + 4;
    return [
      p(cx - half, top, cx - half + t, top, cx + t / 2, join, cx - t / 2, join),
      p(cx + half, top, cx + half - t, top, cx - t / 2, join, cx + t / 2, join),
      p(cx - t / 2, join - 1, cx + t / 2, join - 1, cx + t / 2, bottom, cx - t / 2, bottom),
    ];
  };
  const z = (cx: number) => [
    p(cx - half, top, cx + half, top, cx + half, top + bar, cx - half, top + bar),
    p(cx + half - t, top + bar, cx + half, top + bar, cx - half + t, bottom - bar, cx - half, bottom - bar),
    p(cx - half, bottom - bar, cx + half, bottom - bar, cx + half, bottom, cx - half, bottom),
  ];
  return [...x(276), ...y(DISC.cx), ...z(577)];
}

const LETTERS = letterPolygons();

function MarkRects() {
  return (
    <>
      {MARK.map(([a, b, c, d, e, f, x, y, width, height, stroke], i) => (
        <rect
          key={i}
          transform={`matrix(${a} ${b} ${c} ${d} ${e} ${f})`}
          x={x}
          y={y}
          width={width}
          height={height}
          strokeWidth={stroke}
        />
      ))}
    </>
  );
}

export function G10sXyzLogo({ className }: { className?: string }) {
  const mask = `disc-${useId().replace(/:/g, "")}`;
  return (
    <svg
      viewBox={`0 0 ${LOGO_WIDTH} ${LOGO_HEIGHT}`}
      className={className}
      role="img"
      aria-label="g10s XYZ"
      fill="currentColor"
      stroke="none"
    >
      <defs>
        <mask id={mask} maskUnits="userSpaceOnUse" x="0" y="0" width={LOGO_WIDTH} height={LOGO_HEIGHT}>
          <ellipse {...DISC} fill="white" />
          <g fill="black">
            {LETTERS.map((points) => (
              <polygon key={points} points={points} />
            ))}
          </g>
        </mask>
      </defs>
      <ellipse {...DISC} mask={`url(#${mask})`} />
      <g stroke="currentColor" strokeLinecap="square">
        <MarkRects />
      </g>
    </svg>
  );
}
